#!/usr/bin/env node
// Builds an idempotent SQL import for a course written as Markdown + course.json.
//
// Usage: node scripts/build-course-sql.mjs content/courses/<slug> [out.sql]
// Default output: supabase/content/<slug>.sql
//
// Row ids are derived from the course slug and each item's position, so re-running the
// import updates the same rows instead of duplicating them. New courses start as drafts;
// re-imports never change the publish status. Nothing is deleted, except options that no
// longer exist on an imported question.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("Usage: node scripts/build-course-sql.mjs content/courses/<slug> [out.sql]");
  process.exit(1);
}

const course = JSON.parse(readFileSync(join(dir, "course.json"), "utf8"));
const slug = course.slug ?? basename(dir);
const out = process.argv[3] ?? join("supabase", "content", `${slug}.sql`);

/** Name-based UUID (v5 layout over SHA-1) so ids are stable across runs. */
function uuid(key) {
  const h = createHash("sha1").update(`hope-course:${slug}:${key}`).digest();
  h[6] = (h[6] & 0x0f) | 0x50;
  h[8] = (h[8] & 0x3f) | 0x80;
  const x = h.subarray(0, 16).toString("hex");
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20, 32)}`;
}

const TAG = "$hope$";
function lit(text) {
  const s = String(text ?? "");
  if (s.includes(TAG)) throw new Error(`Text contains the reserved delimiter ${TAG}`);
  return `${TAG}${s}${TAG}`;
}
const es = (text) => (text ? `jsonb_build_object('es', ${lit(text)})` : "NULL");
const num = (n) => (n === undefined || n === null ? "NULL" : Number(n));

function fail(message) {
  console.error(`✖ ${message}`);
  process.exit(1);
}

const sql = [];
const stats = { modules: 0, classes: 0, questions: 0 };
const courseId = uuid("course");
const fe = course.finalExam ?? {};

sql.push(
  `-- Generated by scripts/build-course-sql.mjs from ${dir}. Edit the source files, not this file.`,
  "BEGIN;",
  "",
  "INSERT INTO public.courses (id, title, description, status, final_exam_question_count, final_exam_passing_score, final_exam_time_limit_minutes)",
  `VALUES ('${courseId}', ${es(course.title)}, ${es(course.description)}, 'draft', ${num(fe.questionCount)}, ${num(fe.passingScore ?? 70)}, ${num(fe.timeLimitMinutes)})`,
  "ON CONFLICT (id) DO UPDATE SET title = EXCLUDED.title, description = EXCLUDED.description,",
  "  final_exam_question_count = EXCLUDED.final_exam_question_count,",
  "  final_exam_passing_score = EXCLUDED.final_exam_passing_score,",
  "  final_exam_time_limit_minutes = EXCLUDED.final_exam_time_limit_minutes;",
);

course.modules.forEach((mod, mi) => {
  stats.modules++;
  const subjectId = uuid(`m${mi}`);
  sql.push(
    "",
    `-- Module ${mi + 1}: ${mod.title}`,
    "INSERT INTO public.subjects (id, course_id, title, description, order_index)",
    `VALUES ('${subjectId}', '${courseId}', ${es(mod.title)}, ${es(mod.description)}, ${mi})`,
    "ON CONFLICT (id) DO UPDATE SET course_id = EXCLUDED.course_id, title = EXCLUDED.title,",
    "  description = EXCLUDED.description, order_index = EXCLUDED.order_index;",
  );

  mod.classes.forEach((cls, ci) => {
    stats.classes++;
    const body = readFileSync(join(dir, mod.dir, cls.file), "utf8").trim();
    if (!body) fail(`${mod.dir}/${cls.file} is empty`);
    sql.push(
      "INSERT INTO public.classes (id, subject_id, title, description, content, order_index)",
      `VALUES ('${uuid(`m${mi}/c${ci}`)}', '${subjectId}', ${es(cls.title)}, ${es(cls.description)}, ${es(body)}, ${ci})`,
      "ON CONFLICT (id) DO UPDATE SET subject_id = EXCLUDED.subject_id, title = EXCLUDED.title,",
      "  description = EXCLUDED.description, content = EXCLUDED.content, order_index = EXCLUDED.order_index;",
    );
  });

  const exam = mod.exam;
  if (!exam) return;
  const examId = uuid(`m${mi}/exam`);
  sql.push(
    "INSERT INTO public.exams (id, course_id, subject_id, title, description, passing_score, max_attempts, time_limit_minutes, order_index)",
    `VALUES ('${examId}', '${courseId}', '${subjectId}', ${es(exam.title)}, ${es(exam.description)}, ${num(exam.passingScore ?? 70)}, ${num(exam.maxAttempts ?? 1)}, ${num(exam.timeLimitMinutes)}, ${mod.classes.length})`,
    "ON CONFLICT (id) DO UPDATE SET title = EXCLUDED.title, description = EXCLUDED.description,",
    "  passing_score = EXCLUDED.passing_score, max_attempts = EXCLUDED.max_attempts,",
    "  time_limit_minutes = EXCLUDED.time_limit_minutes, order_index = EXCLUDED.order_index;",
  );

  exam.questions.forEach((q, qi) => {
    stats.questions++;
    const correct = q.options.filter((o) => o.correct).length;
    if (correct !== 1) fail(`${mod.title} question ${qi + 1} needs exactly one correct option (has ${correct})`);
    if (q.options.length < 2) fail(`${mod.title} question ${qi + 1} needs at least two options`);

    const questionId = uuid(`m${mi}/exam/q${qi}`);
    const optionIds = q.options.map((_, oi) => uuid(`m${mi}/exam/q${qi}/o${oi}`));
    sql.push(
      "INSERT INTO public.questions (id, exam_id, content, points, order_index)",
      `VALUES ('${questionId}', '${examId}', ${es(q.text)}, ${num(q.points ?? 1)}, ${qi})`,
      "ON CONFLICT (id) DO UPDATE SET content = EXCLUDED.content, points = EXCLUDED.points, order_index = EXCLUDED.order_index;",
      // Clear the old answer first: only one correct option per question is allowed at any time.
      `UPDATE public.options SET is_correct = false WHERE question_id = '${questionId}';`,
      `DELETE FROM public.options WHERE question_id = '${questionId}' AND id NOT IN (${optionIds.map((id) => `'${id}'`).join(", ")});`,
      "INSERT INTO public.options (id, question_id, content, is_correct) VALUES",
      q.options
        .map((o, oi) => `  ('${optionIds[oi]}', '${questionId}', ${es(o.text)}, ${o.correct ? "true" : "false"})`)
        .join(",\n"),
      "ON CONFLICT (id) DO UPDATE SET content = EXCLUDED.content, is_correct = EXCLUDED.is_correct;",
    );
  });
});

const pool = stats.questions;
if (fe.questionCount && fe.questionCount > pool) {
  fail(`Final exam asks for ${fe.questionCount} questions but the modules only have ${pool}`);
}

sql.push("", "COMMIT;", "");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, sql.join("\n"));
console.log(
  `✔ ${out}: ${stats.modules} modules, ${stats.classes} classes, ${stats.questions} questions (course id ${courseId})`,
);
